CREATE TABLE IF NOT EXISTS tb_trade_notice (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,title VARCHAR(100) NOT NULL,content VARCHAR(1000) NOT NULL,
 order_id BIGINT NULL,is_read TINYINT NOT NULL DEFAULT 0,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_notice_user(user_id,is_read,id)
);
CREATE TABLE IF NOT EXISTS tb_private_message (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,sender_id BIGINT NOT NULL,receiver_id BIGINT NOT NULL,content VARCHAR(1000) NOT NULL,
 product_id BIGINT NULL,is_read TINYINT NOT NULL DEFAULT 0,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_pm_receiver(receiver_id,id),INDEX idx_pm_sender(sender_id,id)
);
CREATE TABLE IF NOT EXISTS tb_user_block (
 user_id BIGINT NOT NULL,target_id BIGINT NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(user_id,target_id)
);
CREATE TABLE IF NOT EXISTS tb_trade_shipment (
 order_id BIGINT PRIMARY KEY,carrier VARCHAR(40) NOT NULL,tracking_no VARCHAR(64) NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS tb_after_sale (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,order_id BIGINT NOT NULL,buyer_id BIGINT NOT NULL,seller_id BIGINT NOT NULL,
 reason VARCHAR(1000) NOT NULL,images TEXT NULL,status VARCHAR(24) NOT NULL DEFAULT 'OPEN',reply VARCHAR(1000) NULL,
 return_carrier VARCHAR(40) NULL,return_tracking VARCHAR(64) NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,UNIQUE KEY uk_case_order(order_id)
);
CREATE TABLE IF NOT EXISTS tb_after_sale_event (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,case_id BIGINT NOT NULL,actor_id BIGINT NOT NULL,action VARCHAR(32) NOT NULL,
 note VARCHAR(1000) NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_case_event(case_id,id)
);
CREATE TABLE IF NOT EXISTS tb_trade_report (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,target_type VARCHAR(16) NOT NULL,target_id BIGINT NOT NULL,
 reason VARCHAR(1000) NOT NULL,images TEXT NULL,status VARCHAR(24) NOT NULL DEFAULT 'PENDING',result VARCHAR(1000) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_report_user(user_id,id)
);
CREATE TABLE IF NOT EXISTS tb_product_draft (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,user_id BIGINT NOT NULL,title VARCHAR(100) NOT NULL,payload TEXT NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,INDEX idx_draft_user(user_id,id)
);
